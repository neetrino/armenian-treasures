export function cultureMenuLabel(locale: SiteLocaleCode, pathOrSlug: string): string | null {
  const key = CULTURE_MENU_PATH_KEYS[pathOrSlug];
  if (!key) return null;
  return pickLocale(MENU_MESSAGES[key], locale);
}

